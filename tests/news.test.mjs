import assert from 'node:assert/strict';
import fs from 'node:fs';
import { build } from 'esbuild';
import { pathToFileURL } from 'node:url';
import os from 'node:os';
import path from 'node:path';
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'circuit-tests-'));
const compiled=path.join(temp,'news.mjs');
await build({entryPoints:['lib/news.ts'],bundle:true,platform:'node',format:'esm',outfile:compiled});
const { validateEdition, publicUrl }=await import(pathToFileURL(compiled).href);
const input=JSON.parse(fs.readFileSync('data/edition.json','utf8'));
const offset=Date.now()-Date.parse(input.generatedAt);
input.generatedAt=new Date().toISOString();
input.stories=input.stories.map(s=>({...s,time:s.time+Math.floor(offset/1000)}));
const edition=validateEdition(input);
assert.equal(edition.stories.length,12);assert.equal(edition.stories[0].id,88000001);assert.equal(edition.candidateCount,30);assert.equal(edition.stories.filter(s=>s.image).length,0);
const imageFixture=validateEdition({...input,stories:input.stories.map((s,i)=>({...s,image:i<7?'https://example.org/fixture-image-'+i+'.png':null}))});assert.equal(imageFixture.stories.filter(s=>s.image).length,7);
assert.ok(edition.stories.every((s,i,a)=>!i||a[i-1].score>=s.score));
for(const bad of ['http://127.0.0.1/','https://localhost/','https://192.168.1.1/','file:///etc/passwd','https://example.local/','https://good.example@localhost/','javascript:alert(1)','http://[::1]/','http://evil.com:8080/'])assert.equal(publicUrl(bad),false,bad);
assert.equal(publicUrl('https://news.ycombinator.com/item?id=1'),true);
assert.throws(()=>validateEdition({...input,stories:[...input.stories,input.stories[0]]}));
assert.throws(()=>validateEdition({...input,stories:[{...input.stories[0],time:0}]}));
assert.throws(()=>validateEdition({...input,stories:[{...input.stories[0],image:'javascript:alert(1)'}]}));
const ties=validateEdition({...input,stories:[{...input.stories[0],score:100,comments:1},{...input.stories[1],score:100,comments:20}]});assert.equal(ties.stories[0].id,input.stories[0].id);
const tiedPrevious={...input,stories:[input.stories[1],input.stories[0]]};
const stable=validateEdition({...input,stories:[{...input.stories[0],score:100,comments:999},{...input.stories[1],score:100,headline:'New wording',comments:1}]},tiedPrevious);assert.equal(stable.stories[0].id,input.stories[1].id);assert.equal(stable.stories[0].headline,input.stories[1].headline);
console.log('PASS: 12-story edition, ranking, eligibility, synthetic image validation, invalid URL protection, duplicate validation, points-only ranking, stable incumbent and unchanged winning headline.');

fs.rmSync(temp,{recursive:true,force:true});
